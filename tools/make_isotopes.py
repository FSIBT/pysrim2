"""Print the natural isotopes of Z = 1..92 as YAML (the source of srim/data/isotopes.yaml).

Run once, from the repository root, and commit the output::

    uv run --with periodictable python tools/make_isotopes.py > srim/data/isotopes.yaml

Only isotopes with a non-zero natural abundance are written, most abundant first. Elements
with no natural isotopes (technetium, promethium, ...) are left out. Masses are in amu and
abundances in percent, as periodictable gives them (IUPAC natural abundances).
"""

import periodictable

MAX_Z = 92

# periodictable gives no natural abundances for uranium (it lists every isotope at 0), so the
# IUPAC values are written in here. Masses still come from periodictable.
ABUNDANCE_OVERRIDES = {
    "U": {234: 0.0054, 235: 0.7204, 238: 99.2742},
}


def natural_isotopes(element):
    """(mass number, mass [amu], abundance [%]) for each isotope with a natural abundance"""
    overrides = ABUNDANCE_OVERRIDES.get(element.symbol, {})
    found = []
    for mass_number in element.isotopes:
        if mass_number == 0:  # 0 is the natural mixture, not an isotope
            continue
        isotope = element[mass_number]
        abundance = overrides.get(mass_number, isotope.abundance)
        if not abundance or abundance <= 0:
            continue
        found.append((mass_number, float(isotope.mass), round(float(abundance), 6)))
    return sorted(found, key=lambda item: item[2], reverse=True)


def main():
    lines = [
        f"# Natural isotopes of Z = 1..{MAX_Z}, from periodictable {periodictable.__version__}",
        "# (IUPAC natural abundances; masses in amu, abundances in percent).",
        "# Generated by: uv run --with periodictable python tools/make_isotopes.py",
        "#   > srim/data/isotopes.yaml",
    ]
    for z in range(1, MAX_Z + 1):
        element = periodictable.elements[z]
        isotopes = natural_isotopes(element)
        if not isotopes:
            continue
        entries = ", ".join(
            f"{{A: {a}, mass_amu: {m!r}, abundance_percent: {p!r}}}" for a, m, p in isotopes
        )
        lines.append(f"{element.symbol}: [{entries}]")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
