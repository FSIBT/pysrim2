"""Slurm: prepare a scan as job folders and an array script, then collect the results.

:func:`prepare_slurm` writes a scan folder that a cluster can run without pysrim2 running on the
login node::

    scan.yaml                 the scan, with its base seed (as run_scan records it)
    jobs/0000/job.yaml ...    job folders (srim.scan.backends format), one unit per point,
                              or one unit per batch of a point with ``batch_ions``
    submit.sbatch             #SBATCH --array=0-<jobs-1>; task k runs pysrim2 run-job jobs/k

Submit it from the scan folder: ``cd <scan folder> && sbatch submit.sbatch`` (the script
changes to ``$SLURM_SUBMIT_DIR``, so no host path is written into it). Each array task runs
one job folder (``pysrim2 run-job``); the outputs go to ``jobs/<k>/out/<point>/``. When the
tasks are done, :func:`collect_slurm` runs the extractors in this process and writes the same
result as a local run (``result/``, the points' folders, the cache). Seeds are the seeds
of :func:`srim.scan.run_scan`, so the two give the same numbers.

Only fixed ion counts (with or without ``batch_ions``): a precision target runs in batches
decided from the results of earlier batches, which needs the parent process (use
``backend="local"`` or ``"container"``).
"""

import logging
import os
import secrets
import shutil
import traceback
from numbers import Integral
from pathlib import Path

from .. import __version__
from ..output import Results
from ..spec import SpecError
from .backends import DONE, ERROR_LOG, OUT_DIR, read_job, write_job
from .batches import MAX_SEED, BatchInfo, derive_seed
from .cache import cache_key
from .executor import (
    _RESERVED,
    _open_cache,
    _summary,
    estimate_batches,
    fixed_batch_sizes,
    mark_scan_folder,
)
from .extract import combine
from .precision import Precision
from .result import ScanResult
from .spec import Scan

log = logging.getLogger(__name__)

SCAN_FILE = "scan.yaml"
JOBS_DIR = "jobs"
SUBMIT_FILE = "submit.sbatch"
#: the error of a point with no outputs yet (its job did not run it, or has not run)
NOT_RUN = "not run yet"
_PRECISION_MESSAGE = "precision targets need the local or container backend; use ions= for Slurm"


def prepare_slurm(scan: Scan, scan_dir, *, jobs=None) -> Path:
    """Write the job folders and ``submit.sbatch`` of ``scan`` into ``scan_dir``.

    Parameters
    ----------
    scan : :class:`~srim.scan.Scan`
        a scan with a fixed ion count (``ions=`` or the base spec's ``number_ions``)
    scan_dir : path-like
        the scan folder (made if missing). It must not hold a prepared scan already.
    jobs : int, optional
        number of job folders; the units (a point, or a batch of a point with ``batch_ions``)
        are dealt round-robin into them. Default: one job per unit. At most one job per unit.

    Returns
    -------
    pathlib.Path
        the scan folder

    Raises
    ------
    SpecError
        for a precision target, a bad ``jobs`` or two points with the same id
    FileExistsError
        when ``scan_dir`` already holds a prepared scan
    """
    if isinstance(scan.ions, Precision):
        raise SpecError(_PRECISION_MESSAGE)
    points = scan.points()
    names = [point.id[:16] for point in points]
    if len(set(names)) != len(names):
        raise SpecError("two scan points have the same id; the scan cannot be prepared")
    folder = Path(os.path.abspath(os.fspath(scan_dir)))
    if (folder / SCAN_FILE).exists() or (folder / JOBS_DIR).exists():
        raise FileExistsError(f"{folder} already holds a prepared scan; choose another folder")
    folder.mkdir(parents=True, exist_ok=True)
    mark_scan_folder(folder)
    base_seed = scan.seed if scan.seed is not None else secrets.randbelow(MAX_SEED) + 1
    _recorded(scan, base_seed).to_yaml(
        folder / SCAN_FILE, provenance={"pysrim2_version": __version__}
    )
    seeds = _seeds(points, base_seed)
    units = _units(scan, points, seeds)
    n_jobs = _job_count(jobs, len(units))
    for k in range(n_jobs):
        members = [unit for i, unit in enumerate(units) if i % n_jobs == k]
        write_job(folder / JOBS_DIR / f"{k:04d}", [(name, spec) for name, _, spec in members])
    script = folder / SUBMIT_FILE
    script.write_text(submit_script(n_jobs), encoding="utf-8")
    script.chmod(0o755)
    return folder


def submit_script(n_jobs: int) -> str:
    """The text of ``submit.sbatch`` for ``n_jobs`` job folders.

    It changes to the directory sbatch was run from (``$SLURM_SUBMIT_DIR``), so submit it
    from the scan folder: ``cd <scan folder> && sbatch submit.sbatch``.
    """
    return (
        "#!/bin/bash\n"
        "#SBATCH --job-name=pysrim2-scan\n"
        f"#SBATCH --array=0-{n_jobs - 1}\n"
        "##SBATCH --time=HH:MM:SS\n"
        "##SBATCH --mem=<size, e.g. 4G>\n"
        "##SBATCH --cpus-per-task=1\n"
        "##SBATCH --partition=<partition>\n"
        "#\n"
        "# Generated by pysrim2 (srim.scan.prepare_slurm). One array task runs one job folder.\n"
        "# Submit from the scan folder: cd <scan folder> && sbatch submit.sbatch\n"
        "# pysrim2 must be on PATH on the compute nodes (load its module, or activate its\n"
        "# environment).\n"
        "set -euo pipefail\n"
        'cd "${SLURM_SUBMIT_DIR:-$PWD}"\n'
        f'JOB_DIR="{JOBS_DIR}/$(printf %04d "$SLURM_ARRAY_TASK_ID")"\n'
        'pysrim2 run-job "$JOB_DIR"\n'
    )


def collect_slurm(scan_dir, *, cache=None) -> ScanResult:
    """Build the result of a prepared scan from its job folders, once the tasks are done.

    Every point is read from its job folder: finished points are copied into
    ``points/<id>/`` and their extractors run here; a point whose unit failed gets status
    ``failed`` with the first line of its ``error.log``; a point whose unit has no outputs
    (not run yet, or still running) gets status ``missing`` with the error ``not run yet``.
    The finished units are stored in the result cache (``cache=`` as for
    :func:`srim.scan.run_scan`: default ``<scan folder>/cache``, ``False`` for none), so a
    later local run of the same scan reuses them. The result is written to ``result/`` as
    ``run_scan`` writes it.

    Raises
    ------
    FileNotFoundError
        when ``scan_dir`` has no ``scan.yaml``
    SpecError
        for a precision scan, a scan without a base seed, or an extractor that cannot be
        imported (``python:`` entries of ``scan.yaml``)
    """
    folder = Path(os.path.abspath(os.fspath(scan_dir)))
    if not (folder / SCAN_FILE).is_file():
        raise FileNotFoundError(f"{folder} has no {SCAN_FILE}; prepare the scan first")
    scan = Scan.from_yaml(folder / SCAN_FILE)
    if isinstance(scan.ions, Precision):
        raise SpecError(_PRECISION_MESSAGE)
    if scan.seed is None:
        raise SpecError(f"{folder / SCAN_FILE}: no base seed; the scan was not prepared")
    points = scan.points()
    seeds = _seeds(points, scan.seed)
    store = _open_cache(cache, folder)
    homes = _job_folders(folder)
    rows = []
    for point, seed in zip(points, seeds, strict=True):
        if scan.batch_ions is None:
            spec = point.spec.with_overrides([f"seed={seed}"])
            job = homes.get(point.id[:16])
            rows.append(_collect_point(scan, point, spec, job, folder, store))
        else:
            rows.append(_collect_batched(scan, point, seed, homes, folder, store))
    result = ScanResult.from_rows(scan, rows, base_dir=folder)
    result.to_csv(folder / "result")
    return result


# -- helpers -----------------------------------------------------------------------------------


def _job_count(jobs, n_units: int) -> int:
    if jobs is None:
        return n_units
    if isinstance(jobs, bool) or not isinstance(jobs, Integral) or jobs < 1:
        raise SpecError(f"jobs must be a whole number >= 1, got {jobs!r}")
    if jobs > n_units:
        raise SpecError(f"jobs={jobs} is more than the {n_units} units (at most one per unit)")
    return int(jobs)


def _unit_name(point_name: str, batch: int | None) -> str:
    """The name of a unit: the point's name, or the point's name and a batch number."""
    return point_name if batch is None else f"{point_name}-b{batch:04d}"


def _units(scan: Scan, points, seeds):
    """The units of the scan, in order: ``(name, point, RunSpec)``. A point is one unit,
    or one unit per batch with ``batch_ions`` (the seeds of :func:`srim.scan.run_scan`)."""
    units = []
    for point, seed in zip(points, seeds, strict=True):
        name = point.id[:16]
        if scan.batch_ions is None:
            units.append((name, point, point.spec.with_overrides([f"seed={seed}"])))
            continue
        sizes = fixed_batch_sizes(point.spec.number_ions, scan.batch_ions)
        for batch, size in enumerate(sizes):
            spec = point.spec.with_overrides(
                [f"number_ions={size}", f"seed={derive_seed(seed, batch)}"]
            )
            units.append((_unit_name(name, batch), point, spec))
    return units


def _seeds(points, base_seed: int) -> list[int]:
    """The seed of each point, as :func:`srim.scan.run_scan` derives it."""
    return [derive_seed(base_seed, int(p.id[:15], 16)) for p in points]


def _recorded(scan: Scan, base_seed: int) -> Scan:
    """``scan`` with the base seed filled in (the file records the seed the run used)."""
    if scan.seed == base_seed:
        return scan
    return Scan(
        scan.base,
        grid=scan.grid,
        points=scan.rows,
        extract=scan.extract,
        ions=scan.ions,
        seed=base_seed,
        batch_ions=scan.batch_ions,
    )


def _job_folders(folder: Path) -> dict[str, Path]:
    """Unit name -> the job folder that holds it, for every job folder of the scan."""
    homes: dict[str, Path] = {}
    jobs = folder / JOBS_DIR
    if not jobs.is_dir():
        return homes
    for job_file in sorted(jobs.glob("*/job.yaml")):
        for name, _spec in read_job(job_file.parent):
            if name in homes:
                raise SpecError(f"the unit {name!r} is in two job folders")
            homes[name] = job_file.parent
    return homes


def _collect_point(scan: Scan, point, spec, job, folder: Path, store):
    index = point.index
    name = point.id[:16]
    dest = folder / "points" / name
    shutil.rmtree(dest, ignore_errors=True)
    out = job / OUT_DIR / name if job is not None else None
    if out is None or not out.is_dir():
        return _row(index, "missing", None, None, None, error=NOT_RUN)
    if (out / DONE).is_file():
        shutil.copytree(out, dest, ignore=shutil.ignore_patterns(DONE, ERROR_LOG))
        _store(store, spec, dest)
        return _extracted(scan, point, dest, spec)
    if (out / ERROR_LOG).is_file():
        dest.mkdir(parents=True)
        shutil.copy2(out / ERROR_LOG, dest / ERROR_LOG)
        first = (out / ERROR_LOG).read_text(encoding="utf-8").splitlines()
        summary = first[0] if first else "the unit failed"
        return _row(index, "failed", None, spec.seed, dest, error=summary)
    return _row(index, "missing", None, None, None, error=NOT_RUN)


def _collect_batched(scan: Scan, point, seed: int, homes, folder: Path, store):
    """The row of a point with ``batch_ions``: its batches are read from their job folders.

    Every finished batch is copied to ``points/<id>/batches/<b>/`` and cached. The point is
    ``done`` when all its batches are, and then its extractors run on the batches merged
    (:func:`srim.scan.executor.estimate_batches`); a failed batch makes the point ``failed``
    with the first line of its ``error.log``; otherwise it is ``missing``.
    """
    index = point.index
    name = point.id[:16]
    dest = folder / "points" / name
    shutil.rmtree(dest, ignore_errors=True)
    sizes = fixed_batch_sizes(point.spec.number_ions, scan.batch_ions)
    specs = [
        point.spec.with_overrides([f"number_ions={size}", f"seed={derive_seed(seed, batch)}"])
        for batch, size in enumerate(sizes)
    ]
    finished, error = 0, None
    for batch, spec in enumerate(specs):
        unit = _unit_name(name, batch)
        job = homes.get(unit)
        out = job / OUT_DIR / unit if job is not None else None
        if out is None or not out.is_dir():
            continue
        target = dest / "batches" / str(batch)
        if (out / DONE).is_file():
            shutil.copytree(out, target, ignore=shutil.ignore_patterns(DONE, ERROR_LOG))
            _store(store, spec, target)
            finished += 1
        elif (out / ERROR_LOG).is_file() and error is None:
            target.mkdir(parents=True, exist_ok=True)
            shutil.copy2(out / ERROR_LOG, target / ERROR_LOG)
            first = (out / ERROR_LOG).read_text(encoding="utf-8").splitlines()
            error = first[0] if first else "the unit failed"
    if error is not None:
        return _row(index, "failed", None, None, dest, error=error)
    if finished < len(specs):
        return _row(index, "missing", None, None, None, error=NOT_RUN)
    return _extracted_batches(scan, point, seed, specs, dest)


def _extracted_batches(scan: Scan, point, seed: int, specs, dest: Path):
    """The row of a finished batched point: the batches' extractors and the batch-means
    estimate run here, in this process (as the local executor does)."""
    index = point.index
    extract = combine(scan.extract)
    n_ions = point.spec.number_ions
    try:
        dirs, infos, batch_values = [], [], []
        for batch, spec in enumerate(specs):
            directory = dest / "batches" / str(batch)
            dirs.append(directory)
            infos.append(BatchInfo(batch, spec.seed, spec.number_ions, directory=str(directory)))
            with Results(str(directory)) as results:
                results.spec = spec.to_dict()
                batch_values.append(dict(extract(results, point)))
        values, errs = estimate_batches(
            extract, point, dirs, infos, point.spec.to_dict(), seed, batch_values
        )
        clash = sorted(set(values) & (set(scan.param_names) | _RESERVED))
        if clash:
            raise ValueError(f"extractor column(s) {clash} clash with the scan's own columns")
    except Exception as exc:
        summary = _summary(exc)
        with open(dest / ERROR_LOG, "a", encoding="utf-8") as f:
            f.write(f"extraction: {summary}\n{traceback.format_exc()}\n")
        return _row(index, "failed", n_ions, seed, dest, error=summary)
    return {
        "index": index,
        "status": "done",
        "n_ions": n_ions,
        "seeds": ",".join(str(spec.seed) for spec in specs),
        "path": str(dest),
        "error": None,
        **values,
        **{f"{name}_err": err for name, err in errs.items()},
    }


def _extracted(scan: Scan, point, dest: Path, spec):
    """The row of a finished point: its extractors run here, in this process."""
    seed = spec.seed
    try:
        with Results(str(dest)) as results:
            results.spec = spec.to_dict()  # ions_in_layer reads the layer edges from it
            values = dict(combine(scan.extract)(results, point))
        clash = sorted(set(values) & (set(scan.param_names) | _RESERVED))
        if clash:
            raise ValueError(f"extractor column(s) {clash} clash with the scan's own columns")
    except Exception as exc:
        summary = _summary(exc)
        with open(dest / ERROR_LOG, "a", encoding="utf-8") as f:
            f.write(f"extraction: {summary}\n{traceback.format_exc()}\n")
        return _row(point.index, "failed", point.spec.number_ions, seed, dest, error=summary)
    return {
        "index": point.index,
        "status": "done",
        "n_ions": point.spec.number_ions,
        "seeds": str(seed),
        "path": str(dest),
        "error": None,
        **values,
    }


def _row(index, status, n_ions, seed, dest, *, error=None):
    """A row without values (failed or not run)."""
    return {
        "index": index,
        "status": status,
        "n_ions": n_ions,
        "seeds": None if seed is None else str(seed),
        "path": None if dest is None else str(dest),
        "error": error,
    }


def _store(store, spec, dest: Path):
    """Keep a finished run in the cache, if its key is not being computed by someone else."""
    if store is None:
        return
    key = cache_key(spec, spec.seed)
    lock = store.try_lock(key)
    if lock is None:
        log.warning("cache entry %s is being written by another scan; not stored", key[:12])
        return
    try:
        store.store(key, dest)
    except OSError as exc:
        log.warning("the run could not be cached (%s)", exc)
    finally:
        lock.release()
